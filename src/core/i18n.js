const DICT = { zh, en };

/** 语言归一:仅 zh / en 两个合法值,其余一律回退 zh(默认语言零回归) */
export const normalizeLang = (v) => (v === 'en' ? 'en' : 'zh');

/**
 * 取值:dict[lang][key] → dict.zh[key] → fallback(英文缺词回退中文,绝不露 key)。
 * fallback 未提供且 key 未命中时返回 key 本身(开发期暴露漏翻,便于补键)。
 */
export const t = (lang, key, fallback) => {
  const v = DICT[normalizeLang(lang)][key] ?? DICT.zh[key];
  return v !== undefined ? v : (fallback !== undefined ? fallback : key);
};

/** 简单占位符替换:fmt('{n} 枚', { n: 3 }) → '3 枚'。值不做转义,含 HTML 时由调用方先 esc。 */
export const fmt = (str, params) => (params
  ? Object.entries(params).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), str)
  : str);

/* ---- 请求级语言上下文(AsyncLocalStorage):server.js 入口写入,视图层读取 ---- */
const reqLang = new AsyncLocalStorage();

/** 在固定语言上下文内执行请求处理(server.js 请求入口调用一次) */
export const runWithLang = (lang, fn) => reqLang.run(normalizeLang(lang), fn);

/** 当前请求的语言;无上下文(脚本/边缘路径)时回退 zh */
export const currentLang = () => reqLang.getStore() || 'zh';
